# Чистка: убрать нулевые заглушки
for _cls, _subs in DATA.items():
    for _k in [k for k, v in _subs.items() if v[0] <= 0]:
        del _subs[_k]


def teacher_for(cls, subj, is_b=False):
    if subj == "Классный час":
        return f"Классный руководитель·{cls}"
    grade = "".join(ch for ch in cls if ch.isdigit())
    suffix = "·2" if is_b else ""
    return f"{subj}·{grade}{suffix}"


def build_rows():
    rows = []
    for cls, subs in DATA.items():
        for subj, (hours, room, split) in subs.items():
            rows.append((cls, subj, hours, teacher_for(cls, subj),
                         "A/B" if split else "",
                         teacher_for(cls, subj, True) if split else "",
                         room or ""))
    return rows


