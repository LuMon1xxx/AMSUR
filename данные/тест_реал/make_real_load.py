            # сплитовые предметы ищут сначала сплит-тег (EN*, IN*), целые — наоборот
            is_split_subj = official in SPLIT_SUBJ
            cand.sort(key=lambda a: (a not in ("EN*", "IN*", "ENP", "ENB")) if is_split_subj else (a in ("EN*", "IN*")))
            key = (cls, cand[0]) if cand else None
            # для сплитов собрать учителей со ВСЕХ родственных тегов (EN+EN* и т.п.)
            found = []
            if key:
                seen = set()
                for c in cand:
                    for t, n in maj.get((cls, c), []):
                        if t not in seen:
                            seen.add(t)
