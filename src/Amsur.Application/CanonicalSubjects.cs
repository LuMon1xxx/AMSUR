namespace Amsur.Application;

// Канонические предметы (D-54, продуктовая поверхность): 23 официальных РБ-названия
// (SUBJECTS_RB.md §1). Серые карточки «нет в нагрузке» и списки диалога строки
// строятся как union(строки, сущности, All): свободный ввод и новые предметы
// сохранены (D-34 flexibility-first). Профильные варианты « (проф)»/« (база)»,
// «Классный час», «Черчение», «Астрономия» — валидные школьные имена, но вне
// ядра-23 (полные карточки по ним — backlog P3).
public static class CanonicalSubjects
{
    public static IReadOnlyList<string> All { get; } =
    [
        "Белорусский язык",
        "Белорусская литература",
        "Русский язык",
        "Русская литература",
        "Человек и мир",
        "Иностранный язык",
        "Математика",
        "Алгебра",
        "Геометрия",
        "История Беларуси",
        "Всемирная история",
        "Обществоведение",
        "География",
        "Биология",
        "Физика",
        "Химия",
        "Информатика",
        "Физическая культура и здоровье",
        "Трудовое обучение",
        "Музыка",
        "Изобразительное искусство",
        "Основы безопасности жизнедеятельности",
        "Допризывная и медицинская подготовка",
    ];

    /// <summary>Каноническое ли имя (без учёта регистра; алиасы «Физра»/«ОБЖ» — нет).</summary>
    public static bool IsCanonical(string name) =>
        All.Contains((name ?? "").Trim(), StringComparer.OrdinalIgnoreCase);
}
